package com.mdsadman.bayan

import android.content.Context
import org.json.JSONObject

/** Bilingual string (English / Bangla). */
data class Bi(val en: String, val bn: String) {
    fun get(lang: String) = if (lang == "bn") bn else en

    companion object {
        fun from(o: JSONObject?): Bi = if (o == null) Bi("", "") else Bi(o.optString("en"), o.optString("bn"))
    }
}

data class TeachC(val id: String, val kind: String, val ar: String, val bi: Bi, val note: Bi?)

data class Item(
    val id: String,
    val ar: String,
    val bi: Bi,
    val root: String?,
    val occ: Int,
    val fam: Boolean,
    val note: Bi?
)

data class Ctx(val kind: String, val title: Bi, val body: Bi)

data class Verse(
    val id: String,
    val ar: String,
    val tokens: List<String>,
    val bi: Bi,
    val ref: String,
    val context: Ctx?
)

data class Lesson(
    val id: String,
    val title: Bi,
    val teaches: List<TeachC>,
    val items: List<Item>,
    val verses: List<Verse>,
    val unit: String
)

data class CourseUnit(val id: String, val num: Int, val title: Bi, val subtitle: Bi, val lessons: List<String>)

/** The whole curriculum, parsed from assets/curriculum.json (generated by curriculum/build.py). */
class Curriculum(
    val units: List<CourseUnit>,
    val lessons: Map<String, Lesson>,
    val items: Map<String, Item>,
    val itemOrder: List<String>,
    val tokens: List<String>,
    val totalQuranWords: Int
) {
    fun unitOf(lessonId: String): CourseUnit? {
        val lid = lessons[lessonId]?.unit ?: return null
        return units.firstOrNull { it.id == lid }
    }

    fun unitItems(unitId: String): List<Item> {
        val u = units.firstOrNull { it.id == unitId } ?: return emptyList()
        val out = LinkedHashMap<String, Item>()
        for (lid in u.lessons) for (it in lessons[lid]?.items ?: emptyList()) out[it.id] = it
        return out.values.toList()
    }

    fun allItems(): List<Item> = itemOrder.mapNotNull { items[it] }

    companion object {
        fun load(ctx: Context): Curriculum {
            val raw = ctx.assets.open("curriculum.json").bufferedReader().use { it.readText() }
            val root = JSONObject(raw)
            val total = root.optInt("totalQuranWords", 77429)
            val itemMap = LinkedHashMap<String, Item>()
            val itemOrder = ArrayList<String>()
            val lessonMap = LinkedHashMap<String, Lesson>()
            val units = ArrayList<CourseUnit>()
            val tokens = LinkedHashSet<String>()

            val unitsArr = root.getJSONArray("units")
            for (ui in 0 until unitsArr.length()) {
                val uo = unitsArr.getJSONObject(ui)
                val lessonIds = ArrayList<String>()
                val lessonsArr = uo.getJSONArray("lessons")
                for (li in 0 until lessonsArr.length()) {
                    val lo = lessonsArr.getJSONObject(li)
                    val resolved = ArrayList<Item>()
                    val itemsArr = lo.optJSONArray("items") ?: org.json.JSONArray()
                    for (ii in 0 until itemsArr.length()) {
                        val io = itemsArr.getJSONObject(ii)
                        if (io.has("ref")) {
                            val ref = io.getString("ref")
                            itemMap[ref]?.let { resolved.add(it) }
                        } else {
                            val item = Item(
                                id = io.getString("id"),
                                ar = io.getString("ar"),
                                bi = Bi(io.getString("en"), io.getString("bn")),
                                root = if (io.has("root")) io.getString("root") else null,
                                occ = io.optInt("occ", 0),
                                fam = io.optBoolean("fam", false),
                                note = if (io.has("note")) Bi.from(io.optJSONObject("note")) else null
                            )
                            itemMap[item.id] = item
                            itemOrder.add(item.id)
                            resolved.add(item)
                        }
                    }
                    val teaches = ArrayList<TeachC>()
                    val tArr = lo.optJSONArray("teaches") ?: org.json.JSONArray()
                    for (ti in 0 until tArr.length()) {
                        val t = tArr.getJSONObject(ti)
                        teaches.add(
                            TeachC(
                                id = t.getString("id"),
                                kind = t.optString("kind", "word"),
                                ar = t.getString("ar"),
                                bi = Bi(t.getString("en"), t.getString("bn")),
                                note = if (t.has("note")) Bi.from(t.optJSONObject("note")) else null
                            )
                        )
                    }
                    val verses = ArrayList<Verse>()
                    val vArr = lo.optJSONArray("verses") ?: org.json.JSONArray()
                    for (vi in 0 until vArr.length()) {
                        val v = vArr.getJSONObject(vi)
                        val tk = ArrayList<String>()
                        val tkArr = v.getJSONArray("tokens")
                        for (ki in 0 until tkArr.length()) {
                            tk.add(tkArr.getString(ki))
                            tokens.add(tkArr.getString(ki))
                        }
                        val cx = if (v.has("context")) v.getJSONObject("context") else null
                        verses.add(
                            Verse(
                                id = v.getString("id"),
                                ar = v.getString("ar"),
                                tokens = tk,
                                bi = Bi(v.getString("en"), v.getString("bn")),
                                ref = v.getString("ref"),
                                context = if (cx == null) null else Ctx(
                                    kind = cx.optString("kind", "theme"),
                                    title = Bi.from(cx.optJSONObject("title")),
                                    body = Bi.from(cx.optJSONObject("body"))
                                )
                            )
                        )
                    }
                    val lesson = Lesson(
                        id = lo.getString("id"),
                        title = Bi.from(lo.getJSONObject("title")),
                        teaches = teaches,
                        items = resolved,
                        verses = verses,
                        unit = uo.getString("id")
                    )
                    lessonMap[lesson.id] = lesson
                    lessonIds.add(lesson.id)
                }
                units.add(
                    CourseUnit(
                        id = uo.getString("id"),
                        num = uo.optInt("num"),
                        title = Bi.from(uo.getJSONObject("title")),
                        subtitle = Bi.from(uo.getJSONObject("subtitle")),
                        lessons = lessonIds
                    )
                )
            }
            return Curriculum(units, lessonMap, itemMap, itemOrder, tokens.toList(), total)
        }
    }
}
