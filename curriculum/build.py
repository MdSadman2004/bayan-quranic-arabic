"""Bayan curriculum build: validate unit files, merge, emit web + android payloads.

Usage: python curriculum/build.py
Outputs:
  dist/curriculum.json
  web/js/data.js
  android/app/src/main/assets/curriculum.json
"""
from __future__ import annotations

import copy
from dataclasses import dataclass, field
import json
import os
from pathlib import Path
import re
import sys
import tempfile
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
ID_RE = re.compile(r"[A-Za-z0-9_\-]+\Z")
UNIT_ID_RE = re.compile(r"u[1-9][0-9]*\Z")
VERSE_REF_RE = re.compile(r"\b([0-9]+):([0-9]+)(?:[–\-]([0-9]+))?")
# Al-Baqarah (2:286) is the longest surah, so any ayah number above it is bogus.
MAX_AYAH = 286
JS_PREFIX = "// generated by curriculum/build.py - do not edit\nwindow.BAYAN_CURRICULUM = "
FEATURE_KINDS = {"word", "concept", "phrase"}
SEED_KINDS = {"etymology", "agency", "permanence", "pairs", "silence", "tazkiyah"}
LOOT_KINDS = {"relic", "scroll", "shield"}


def _text(value, where: str, errors: list[str]) -> bool:
    if not isinstance(value, str) or not value.strip():
        errors.append(f"{where}: expected a nonempty string")
        return False
    return True


def _bilingual(value, where: str, errors: list[str]) -> None:
    if not isinstance(value, dict):
        errors.append(f"{where}: expected an object with 'en' and 'bn'")
        return
    for lang in ("en", "bn"):
        _text(value.get(lang), f"{where}.{lang}", errors)


def _items(value, where: str, errors: list[str], minimum: int = 1) -> list:
    if not isinstance(value, list) or len(value) < minimum:
        errors.append(f"{where}: expected an array of at least {minimum}")
        return []
    return value


def _unique_ids(nodes: list, where: str, errors: list[str]) -> None:
    seen: set[str] = set()
    for index, node in enumerate(nodes):
        if not isinstance(node, dict):
            errors.append(f"{where}[{index}]: expected an object")
            continue
        node_id = node.get("id")
        if not _text(node_id, f"{where}[{index}].id", errors):
            continue
        if node_id in seen:
            errors.append(f"{where}[{index}].id: duplicate id '{node_id}'")
        seen.add(node_id)


def _verse_link(node: dict, where: str, verse_ids: set[str], errors: list[str]) -> None:
    """A feature may point at a bundled verse id or spell out a Quran reference."""
    ref = node.get("verse")
    if ref is None:
        return
    if not isinstance(ref, str) or not ref.strip():
        errors.append(f"{where}.verse: expected a verse id or a Quran reference")
        return
    if ref.startswith("v_"):
        if ref not in verse_ids:
            errors.append(f"{where}.verse: '{ref}' is not a bundled verse id")
        return
    match = VERSE_REF_RE.search(ref)
    if not match or not (1 <= int(match[1]) <= 114 and 1 <= int(match[2]) <= MAX_AYAH):
        errors.append(f"{where}.verse: expected a bundled verse id or a Quran reference")


def validate_features(features, verse_ids: set[str]) -> list[str]:
    """Validate the game/wisdom/rite payload shared by both clients."""
    errors: list[str] = []
    if not isinstance(features, dict):
        return ["features: expected an object"]
    for key in ("combo", "chests", "forge", "boss", "seeds", "rites", "whispers", "loaders", "halaqah", "illumination"):
        if key not in features:
            errors.append(f"features.{key}: missing")
    if errors:
        return errors

    combo = features["combo"]
    steps = _items(combo.get("steps"), "features.combo.steps", errors, 2)
    semitones = _items(combo.get("semitones"), "features.combo.semitones", errors, 2)
    if len(steps) != len(semitones):
        errors.append("features.combo: steps and semitones must have the same length")
    if steps and not all(type(s) is int and 1 < s <= 20 for s in steps):
        errors.append("features.combo.steps: expected multipliers above 1, at most 20")
    if steps and steps != sorted(steps):
        errors.append("features.combo.steps: multipliers must ascend")
    window = combo.get("windowSec")
    if type(window) is not int or not 1 <= window <= 60:
        errors.append("features.combo.windowSec: expected seconds between 1 and 60")
    _bilingual(combo.get("note"), "features.combo.note", errors)

    chests = features["chests"]
    chance = chests.get("chance")
    if not isinstance(chance, (int, float)) or isinstance(chance, bool) or not 0 <= chance <= 1:
        errors.append("features.chests.chance: expected a probability between 0 and 1")
    _unique_ids(_items(chests.get("rarities"), "features.chests.rarities", errors), "features.chests.rarities", errors)
    for index, rarity in enumerate(chests.get("rarities", [])):
        if isinstance(rarity, dict):
            if type(rarity.get("weight")) is not int or rarity["weight"] <= 0:
                errors.append(f"features.chests.rarities[{index}].weight: expected a positive integer")
            _bilingual(rarity.get("label"), f"features.chests.rarities[{index}].label", errors)
    _unique_ids(_items(chests.get("kinds"), "features.chests.kinds", errors), "features.chests.kinds", errors)
    loot = _items(chests.get("loot"), "features.chests.loot", errors, 3)
    _unique_ids(loot, "features.chests.loot", errors)
    rarity_ids = {r.get("id") for r in chests.get("rarities", []) if isinstance(r, dict)}
    for index, entry in enumerate(loot):
        if not isinstance(entry, dict):
            continue
        where = f"features.chests.loot[{index}]"
        if entry.get("kind") not in LOOT_KINDS:
            errors.append(f"{where}.kind: expected relic, scroll or shield")
        if entry.get("rarity") not in rarity_ids:
            errors.append(f"{where}.rarity: '{entry.get('rarity')}' is not a declared rarity")
        _bilingual(entry.get("title"), f"{where}.title", errors)
        _bilingual(entry.get("body"), f"{where}.body", errors)
        _verse_link(entry, where, verse_ids, errors)
        if entry.get("kind") == "relic" and entry.get("root") is not None:
            root = entry["root"]
            if not (isinstance(root, str) and len(root.split(" ")) == 3 and all(
                    len(c) == 1 and unicodedata.category(c) == "Lo" and "ARABIC" in unicodedata.name(c, "")
                    for c in root.split(" "))):
                errors.append(f"{where}.root: expected 3 space-separated Arabic letters")

    forge = features["forge"]
    _bilingual(forge.get("name"), "features.forge.name", errors)
    _bilingual(forge.get("note"), "features.forge.note", errors)
    moulds = _items(forge.get("moulds"), "features.forge.moulds", errors, 2)
    _unique_ids(moulds, "features.forge.moulds", errors)
    for index, mould in enumerate(moulds):
        if not isinstance(mould, dict):
            continue
        where = f"features.forge.moulds[{index}]"
        _text(mould.get("pattern"), f"{where}.pattern", errors)
        _bilingual(mould.get("role"), f"{where}.role", errors)
        examples = _items(mould.get("examples"), f"{where}.examples", errors, 2)
        for j, example in enumerate(examples):
            if not isinstance(example, dict):
                errors.append(f"{where}.examples[{j}]: expected an object")
                continue
            _text(example.get("word"), f"{where}.examples[{j}].word", errors)
            _bilingual(example.get("meaning"), f"{where}.examples[{j}].meaning", errors)
            root = example.get("root")
            if not (isinstance(root, str) and len(root.split(" ")) == 3):
                errors.append(f"{where}.examples[{j}].root: expected 3 space-separated Arabic letters")

    boss = features["boss"]
    _bilingual(boss.get("name"), "features.boss.name", errors)
    _bilingual(boss.get("note"), "features.boss.note", errors)
    if type(boss.get("seconds")) is not int or not 10 <= boss["seconds"] <= 600:
        errors.append("features.boss.seconds: expected seconds between 10 and 600")
    waves = _items(boss.get("waves"), "features.boss.waves", errors, 4)
    _unique_ids(waves, "features.boss.waves", errors)
    for index, wave in enumerate(waves):
        if not isinstance(wave, dict):
            continue
        where = f"features.boss.waves[{index}]"
        _bilingual(wave.get("trap"), f"{where}.trap", errors)
        _bilingual(wave.get("note"), f"{where}.note", errors)
        options = _items(wave.get("options"), f"{where}.options", errors, 2)
        answer = wave.get("answer")
        if type(answer) is not int or not 0 <= answer < max(1, len(options)):
            errors.append(f"{where}.answer: expected an index into options")
        for j, option in enumerate(options):
            _bilingual(option, f"{where}.options[{j}]", errors)

    seeds = features["seeds"]
    _bilingual(seeds.get("name"), "features.seeds.name", errors)
    _bilingual(seeds.get("note"), "features.seeds.note", errors)
    seed_items = _items(seeds.get("items"), "features.seeds.items", errors, 6)
    _unique_ids(seed_items, "features.seeds.items", errors)
    for index, seed in enumerate(seed_items):
        if not isinstance(seed, dict):
            continue
        where = f"features.seeds.items[{index}]"
        if seed.get("kind") not in SEED_KINDS:
            errors.append(f"{where}.kind: expected one of {', '.join(sorted(SEED_KINDS))}")
        _bilingual(seed.get("title"), f"{where}.title", errors)
        _bilingual(seed.get("body"), f"{where}.body", errors)
        _text(seed.get("word"), f"{where}.word", errors)
        _verse_link(seed, where, verse_ids, errors)

    rites = features["rites"]
    if not isinstance(rites, dict):
        errors.append("features.rites: expected an object")
    else:
        for key in ("salah", "waqt", "wuduAdhan", "jumuah", "sawm", "zakatHajj"):
            section = rites.get(key)
            if not isinstance(section, dict):
                errors.append(f"features.rites.{key}: expected an object")
                continue
            _bilingual(section.get("name"), f"features.rites.{key}.name", errors)
            _bilingual(section.get("note"), f"features.rites.{key}.note", errors)
        salah_steps = _items(rites.get("salah", {}).get("steps"), "features.rites.salah.steps", errors, 5)
        _unique_ids(salah_steps, "features.rites.salah.steps", errors)
        for index, step in enumerate(salah_steps):
            if not isinstance(step, dict):
                continue
            where = f"features.rites.salah.steps[{index}]"
            _bilingual(step.get("posture"), f"{where}.posture", errors)
            _bilingual(step.get("grammar"), f"{where}.grammar", errors)
            for field in ("ar", "en", "bn"):
                _text(step.get(field), f"{where}.{field}", errors)
        windows = _items(rites.get("waqt", {}).get("windows"), "features.rites.waqt.windows", errors, 5)
        _unique_ids(windows, "features.rites.waqt.windows", errors)
        for index, window_node in enumerate(windows):
            if not isinstance(window_node, dict):
                continue
            where = f"features.rites.waqt.windows[{index}]"
            _bilingual(window_node.get("name"), f"{where}.name", errors)
            _bilingual(window_node.get("focus"), f"{where}.focus", errors)
            _verse_link(window_node, where, verse_ids, errors)
            if window_node.get("verse") is None:
                errors.append(f"{where}.verse: missing")
        for key, field in (("wuduAdhan", "items"), ("zakatHajj", "items")):
            entries = _items(rites.get(key, {}).get(field), f"features.rites.{key}.{field}", errors, 2)
            _unique_ids(entries, f"features.rites.{key}.{field}", errors)
            for index, entry in enumerate(entries):
                if not isinstance(entry, dict):
                    continue
                where = f"features.rites.{key}.{field}[{index}]"
                _text(entry.get("term"), f"{where}.term", errors)
                _bilingual(entry.get("title"), f"{where}.title", errors)
                _bilingual(entry.get("body"), f"{where}.body", errors)
        phrases = _items(rites.get("jumuah", {}).get("phrases"), "features.rites.jumuah.phrases", errors, 3)
        _unique_ids(phrases, "features.rites.jumuah.phrases", errors)
        for index, phrase in enumerate(phrases):
            if isinstance(phrase, dict):
                _text(phrase.get("ar"), f"features.rites.jumuah.phrases[{index}].ar", errors)
        drills = _items(rites.get("sawm", {}).get("drills"), "features.rites.sawm.drills", errors, 2)
        _unique_ids(drills, "features.rites.sawm.drills", errors)
        for index, drill in enumerate(drills):
            if not isinstance(drill, dict):
                continue
            where = f"features.rites.sawm.drills[{index}]"
            _bilingual(drill.get("ask"), f"{where}.ask", errors)
            _verse_link(drill, where, verse_ids, errors)
            if drill.get("verse") is None:
                errors.append(f"{where}.verse: missing")
            options = _items(drill.get("options"), f"{where}.options", errors, 2)
            answer = drill.get("answer")
            if type(answer) is not int or not 0 <= answer < max(1, len(options)):
                errors.append(f"{where}.answer: expected an index into options")

    whispers = _items(features["whispers"], "features.whispers", errors, 4)
    _unique_ids(whispers, "features.whispers", errors)
    for index, whisper in enumerate(whispers):
        if isinstance(whisper, dict):
            _bilingual(whisper.get("line"), f"features.whispers[{index}].line", errors)

    loaders = _items(features["loaders"], "features.loaders", errors, 6)
    _unique_ids(loaders, "features.loaders", errors)
    for index, loader in enumerate(loaders):
        if isinstance(loader, dict):
            _bilingual(loader.get("name"), f"features.loaders[{index}].name", errors)
            if type(loader.get("seconds")) is not int or loader["seconds"] < 0:
                errors.append(f"features.loaders[{index}].seconds: expected a non-negative integer")

    halaqah = features["halaqah"]
    if isinstance(halaqah, dict):
        _bilingual(halaqah.get("name"), "features.halaqah.name", errors)
        _bilingual(halaqah.get("note"), "features.halaqah.note", errors)
        if type(halaqah.get("maxMembers")) is not int or not 2 <= halaqah["maxMembers"] <= 12:
            errors.append("features.halaqah.maxMembers: expected between 2 and 12")
    else:
        errors.append("features.halaqah: expected an object")

    illumination = features["illumination"]
    if isinstance(illumination, dict):
        _bilingual(illumination.get("name"), "features.illumination.name", errors)
        _bilingual(illumination.get("note"), "features.illumination.note", errors)
    else:
        errors.append("features.illumination: expected an object")
    return errors


@dataclass
class ValidationResult:
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    corpus: dict | None = None
    stats: dict[str, int] = field(default_factory=dict)

    @property
    def valid(self) -> bool:
        return not self.errors and self.corpus is not None


class _Validator:
    """One traversal, matching the clients' definition-before-reference index."""

    def __init__(self) -> None:
        self.result = ValidationResult()
        self.ids: dict[str, str] = {}
        self.items: dict[str, dict] = {}
        self.pending_refs: list[tuple[str, str]] = []
        self.nums: set[int] = set()
        self.verse_ids: set[str] = set()
        self.counts = dict(units=0, lessons=0, teaches=0, verses=0, contexts=0)

    def error(self, where: str, message: str) -> None:
        self.result.errors.append(f"{where}: {message}")

    def obj(self, value, where: str) -> bool:
        if not isinstance(value, dict):
            self.error(where, "expected an object")
            return False
        return True

    def string(self, value, where: str) -> bool:
        if not isinstance(value, str) or not value.strip():
            self.error(where, "expected a nonempty string")
            return False
        return True

    def positive(self, value, where: str) -> bool:
        if type(value) is not int or value <= 0:
            self.error(where, "expected a positive integer (not boolean)")
            return False
        return True

    def array(self, value, where: str) -> list:
        if not isinstance(value, list) or not value:
            self.error(where, "expected a nonempty array")
            return []
        return value

    def bilingual(self, value, where: str) -> None:
        if self.obj(value, where):
            for lang in ("en", "bn"):
                self.string(value.get(lang), f"{where}.{lang}")

    def identifier(self, value, where: str, reserve: bool = True) -> bool:
        if not self.string(value, where):
            return False
        if not ID_RE.fullmatch(value):
            self.error(where, "expected an id containing only letters, digits, '_' or '-'")
            return False
        if reserve:
            if value in self.ids:
                self.error(where, f"duplicate id '{value}'; first defined at {self.ids[value]}")
            else:
                self.ids[value] = where
        return True

    def text_node(self, node: dict, where: str) -> None:
        self.identifier(node.get("id"), f"{where}.id")
        for key in ("ar", "en", "bn"):
            self.string(node.get(key), f"{where}.{key}")
        if "note" in node:
            self.bilingual(node["note"], f"{where}.note")

    def item(self, node, where: str) -> None:
        if not self.obj(node, where):
            return
        if "ref" in node:
            if set(node) != {"ref"}:
                self.error(where, "an item ref must contain only 'ref', not definition fields")
            ref = node["ref"]
            if self.identifier(ref, f"{where}.ref", reserve=False) and ref not in self.items:
                self.pending_refs.append((ref, where))
            return
        self.text_node(node, where)
        root = node.get("root")
        if "root" in node:
            # Unicode letters only: Arabic diacritics and punctuation are not roots.
            if not (isinstance(root, str) and len(root.split(" ")) == 3 and all(
                len(c) == 1 and unicodedata.category(c) == "Lo"
                and "ARABIC" in unicodedata.name(c, "") for c in root.split(" ")
            )):
                self.error(f"{where}.root", "expected 3 space-separated Arabic letters")
        if "occ" in node:
            self.positive(node["occ"], f"{where}.occ")
        if "fam" in node and type(node["fam"]) is not bool:
            self.error(f"{where}.fam", "expected a boolean")
        nid = node.get("id")
        if isinstance(nid, str) and ID_RE.fullmatch(nid):
            self.items.setdefault(nid, node)

    def verse(self, node, where: str) -> None:
        if not self.obj(node, where):
            return
        self.counts["verses"] += 1
        verse_id = node.get("id")
        if isinstance(verse_id, str):
            self.verse_ids.add(verse_id)
        self.text_node(node, where)
        tokens = self.array(node.get("tokens"), f"{where}.tokens")
        good_tokens = bool(tokens)
        for i, token in enumerate(tokens):
            if not self.string(token, f"{where}.tokens[{i}]"):
                good_tokens = False
            elif any(c.isspace() for c in token):
                self.error(f"{where}.tokens[{i}]", "expected one token without whitespace")
                good_tokens = False
        if good_tokens and " ".join(tokens) != node.get("ar"):
            self.error(where, "tokens do not join to ar with single spaces")
        ref = node.get("ref")
        if self.string(ref, f"{where}.ref"):
            match = VERSE_REF_RE.search(ref)
            if not match or not (1 <= int(match[1]) <= 114 and 1 <= int(match[2]) <= MAX_AYAH
                                  and (match[3] is None or int(match[2]) <= int(match[3]) <= MAX_AYAH)):
                self.error(f"{where}.ref", "expected a Quran source reference, e.g. Al-Ikhlas 112:1–4")
        if "context" in node:
            ctx = node["context"]
            if self.obj(ctx, f"{where}.context"):
                self.counts["contexts"] += 1
                if ctx.get("kind") not in ("asbab", "story", "theme", "others"):
                    self.error(f"{where}.context.kind", "expected asbab, story, theme or others")
                for key in ("title", "body"):
                    self.bilingual(ctx.get(key), f"{where}.context.{key}")

    def lesson(self, node, where: str) -> None:
        if not self.obj(node, where):
            return
        self.counts["lessons"] += 1
        self.identifier(node.get("id"), f"{where}.id")
        self.bilingual(node.get("title"), f"{where}.title")
        teaches = self.array(node.get("teaches"), f"{where}.teaches")
        for i, teach in enumerate(teaches):
            loc = f"{where}.teaches[{i}]"
            if self.obj(teach, loc):
                self.counts["teaches"] += 1
                self.text_node(teach, loc)
                if teach.get("kind") not in ("word", "concept", "phrase"):
                    self.error(f"{loc}.kind", "expected word, concept or phrase")
        items = self.array(node.get("items"), f"{where}.items")
        for i, item in enumerate(items):
            self.item(item, f"{where}.items[{i}]")
        if len(items) < 4:
            self.result.warnings.append(f"{where}: only {len(items)} items")
        for i, verse in enumerate(self.array(node.get("verses"), f"{where}.verses")):
            self.verse(verse, f"{where}.verses[{i}]")

    def unit(self, node, index: int, order: list) -> None:
        where = f"units[{index}]"
        if not self.obj(node, where):
            return
        self.counts["units"] += 1
        uid = node.get("id")
        self.identifier(uid, f"{where}.id")
        if index < len(order) and uid != order[index]:
            self.error(f"{where}.id", f"expected '{order[index]}' from unitOrder, got {uid!r}")
        num = node.get("num")
        if self.positive(num, f"{where}.num"):
            if num in self.nums:
                self.error(f"{where}.num", f"duplicate unit number {num}")
            self.nums.add(num)
            if num != index + 1:
                self.error(f"{where}.num", f"expected {index + 1} in unitOrder sequence")
        for key in ("title", "subtitle"):
            self.bilingual(node.get(key), f"{where}.{key}")
        for i, lesson in enumerate(self.array(node.get("lessons"), f"{where}.lessons")):
            self.lesson(lesson, f"{where}.lessons[{i}]")


def validate_curriculum(meta, units, features=None) -> ValidationResult:
    """Validate in-memory fixtures or the real corpus, without global error state.

    Returns a detached merged corpus only on success. Diagnostics always identify
    the failing path; malformed JSON shapes produce errors rather than exceptions.
    """
    validator = _Validator()
    result = validator.result
    if not validator.obj(meta, "meta"):
        return result
    app = meta.get("app")
    if validator.obj(app, "meta.app"):
        for key in ("name", "nameAr"):
            validator.string(app.get(key), f"meta.app.{key}")
        validator.bilingual(app.get("tagline"), "meta.app.tagline")
    for key in ("version", "totalQuranWords"):
        validator.positive(meta.get(key), f"meta.{key}")
    order = validator.array(meta.get("unitOrder"), "meta.unitOrder")
    seen_order: set[str] = set()
    for i, uid in enumerate(order):
        where = f"meta.unitOrder[{i}]"
        if not isinstance(uid, str) or not UNIT_ID_RE.fullmatch(uid):
            validator.error(where, "expected a unit id such as 'u1' (no paths)")
        elif uid in seen_order:
            validator.error(where, f"duplicate unitOrder id '{uid}'")
        else:
            seen_order.add(uid)
    unit_list = validator.array(units, "units")
    if len(unit_list) != len(order):
        validator.error("units", f"expected {len(order)} units from unitOrder; got {len(unit_list)}")
    for i, unit in enumerate(unit_list):
        validator.unit(unit, i, order)
    for ref, where in validator.pending_refs:
        if ref in validator.items:
            validator.error(where, f"forward item ref '{ref}'; define the item earlier in unitOrder/lesson/item order (clients resolve in one pass)")
        else:
            validator.error(where, f"item ref '{ref}' does not resolve to an item definition")
    if features is not None:
        result.errors.extend(validate_features(features, validator.verse_ids))
    result.stats = dict(validator.counts, items=len(validator.items), roots=len({
        item["root"] for item in validator.items.values() if isinstance(item.get("root"), str)
    }))
    if not result.errors:
        corpus = {
            "app": meta["app"], "version": meta["version"],
            "totalQuranWords": meta["totalQuranWords"], "units": units,
        }
        if features is not None:
            corpus["features"] = features
        result.corpus = copy.deepcopy(corpus)
    return result


def load_curriculum(directory: Path) -> ValidationResult:
    """Read only declared units, rejecting malformed/unsafe order ids first."""
    errors: list[str] = []

    def read(path: Path):
        try:
            return json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            errors.append(f"{path}: cannot read JSON: {exc}")
            return None

    meta = read(directory / "meta.json")
    order = meta.get("unitOrder") if isinstance(meta, dict) else None
    units = []
    if isinstance(order, list):
        for uid in order:
            if isinstance(uid, str) and UNIT_ID_RE.fullmatch(uid):
                units.append(read(directory / "units" / f"{uid}.json"))
    features = read(directory / "features.json")
    if features is None:
        errors.append(f"{directory / 'features.json'}: missing game/wisdom payload")
    result = validate_curriculum(meta, units, features)
    result.errors[:0] = errors
    if result.errors:
        result.corpus = None
    return result


def render_outputs(corpus: dict, root: Path) -> dict[Path, str]:
    compact = json.dumps(corpus, ensure_ascii=False, separators=(",", ":"))
    return {
        root / "dist/curriculum.json": json.dumps(corpus, ensure_ascii=False, indent=1),
        root / "web/js/data.js": JS_PREFIX + compact + ";\n",
        root / "android/app/src/main/assets/curriculum.json": compact,
        # The Android client parses features.json separately from the curriculum.
        root / "android/app/src/main/assets/features.json": json.dumps(
            corpus.get("features", {}), ensure_ascii=False, indent=1
        ) + "\n",
    }


def _stage(target: Path, content: bytes) -> Path:
    with tempfile.NamedTemporaryFile(prefix=f".{target.name}.", suffix=".tmp",
                                     dir=target.parent, delete=False) as handle:
        path = Path(handle.name)
        try:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        except BaseException:
            handle.close()
            path.unlink(missing_ok=True)
            raise
    return path


def publish_outputs(outputs: dict[Path, str]) -> None:
    """Stage every payload before atomic per-file replacement; roll back I/O failures.

    Readers (including Gradle) see a complete old or new file, never truncated
    JSON. Filesystems do not provide a cross-directory atomic transaction; a
    process/OS crash during replacement can require rerunning the build.
    """
    staged: dict[Path, Path] = {}
    backups: dict[Path, Path | None] = {}
    replaced: list[Path] = []
    try:
        for target, text in outputs.items():
            target.parent.mkdir(parents=True, exist_ok=True)
            backups[target] = _stage(target, target.read_bytes()) if target.exists() else None
            staged[target] = _stage(target, text.encode("utf-8"))
        for target, temporary in staged.items():
            os.replace(temporary, target)
            replaced.append(target)
    except OSError:
        for target in reversed(replaced):
            backup = backups[target]
            if backup is None:
                target.unlink(missing_ok=True)
            else:
                os.replace(backup, target)
        raise
    finally:
        for path in [*staged.values(), *backups.values()]:
            if path is not None:
                path.unlink(missing_ok=True)


def build(root: Path = ROOT) -> ValidationResult:
    result = load_curriculum(root / "curriculum")
    if result.valid:
        try:
            publish_outputs(render_outputs(result.corpus, root))
        except (OSError, ValueError, TypeError) as exc:
            result.errors.append(f"output generation failed: {exc}")
            result.corpus = None
    return result


def main(root: Path = ROOT) -> int:
    result = build(root)
    if not result.valid:
        for error in result.errors:
            print(f"ERROR {error}")
        print(f"-- {len(result.errors)} error(s)")
        return 1
    counts = result.stats
    print(f"OK  units={counts['units']}  lessons={counts['lessons']}  teaches={counts['teaches']}")
    print(f"    items(unique)={counts['items']}  verses={counts['verses']}  contexts={counts['contexts']}  roots={counts['roots']}")
    for warning in result.warnings:
        print(f"WARN {warning}")
    print("wrote dist/curriculum.json, web/js/data.js, android assets/curriculum.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
